function renderPalettePans() {
  const container = document.getElementById("palettePans");
  if (!container) return;

  container.innerHTML = PALETTE_SHADES.map((shade, idx) => `
    <button type="button" class="pan-item ${idx === activeShadeIndex ? 'active' : ''}"
            style="background: ${shade.color};"
            title="${shade.title} - ${shade.finish}"
            onclick="selectShade(${idx})">
    </button>
  `).join("");
}

function selectShade(index) {
  if (index < 0 || index >= PALETTE_SHADES.length) return;
  activeShadeIndex = index;
  const shade = PALETTE_SHADES[index];

  const titleEl = document.getElementById("shadeTitle");
  const finishEl = document.getElementById("shadeFinish");
  const descEl = document.getElementById("shadeDescription");
  const circleEl = document.getElementById("shadeCircle");
  const lineEl = document.getElementById("swatchLine");

  if (titleEl) titleEl.textContent = shade.title;
  if (finishEl) finishEl.textContent = shade.finish;
  if (descEl) descEl.textContent = shade.desc;
  if (circleEl) circleEl.style.backgroundColor = shade.color;
  if (lineEl) {
    lineEl.style.background = `linear-gradient(90deg, ${shade.color} 0%, #FFFFFF 50%, ${shade.color} 100%)`;
  }

  renderPalettePans();
}


// Estado del Carrito y Configuración
const CART_STORAGE_KEY = "melindas_cart_items";
const FREE_SHIPPING_LIMIT = 120000;
const WHATSAPP_PHONE = "573175276404";

let cart = [];

function loadCart() {
  try {
    const saved = localStorage.getItem(CART_STORAGE_KEY);
    cart = saved ? JSON.parse(saved) : [];
  } catch(e) {
    cart = [];
  }
  updateCartUI();
}

function saveCart() {
  try {
    localStorage.setItem(CART_STORAGE_KEY, JSON.stringify(cart));
  } catch(e) {}
  updateCartUI();
}

function addToCart(productId, title, price, image, variant = "Estándar") {
  const existing = cart.find(item => item.id === productId && item.variant === variant);
  if (existing) {
    existing.quantity += 1;
  } else {
    cart.push({
      id: productId,
      title: title,
      price: price,
      image: image,
      variant: variant,
      quantity: 1
    });
  }
  saveCart();
  showToast(`Añadido: ${title}`);
  openCart();
}

function updateQuantity(productId, variant, delta) {
  const item = cart.find(i => i.id === productId && i.variant === variant);
  if (!item) return;
  item.quantity += delta;
  if (item.quantity <= 0) {
    cart = cart.filter(i => !(i.id === productId && i.variant === variant));
  }
  saveCart();
}

function removeFromCart(productId, variant) {
  cart = cart.filter(i => !(i.id === productId && i.variant === variant));
  saveCart();
}

function getCartSubtotal() {
  return cart.reduce((acc, item) => acc + (item.price * item.quantity), 0);
}

function getCartTotalCount() {
  return cart.reduce((acc, item) => acc + item.quantity, 0);
}

function updateCartUI() {
  const countBadge = document.querySelectorAll(".cart-count-badge");
  const totalCount = getCartTotalCount();
  countBadge.forEach(el => {
    el.textContent = totalCount;
    el.style.display = totalCount > 0 ? "inline-flex" : "none";
  });

  const cartList = document.getElementById("cartItemsList");
  const subtotalEl = document.getElementById("cartSubtotalText");
  const shippingBar = document.getElementById("shippingProgressBar");
  const shippingMsg = document.getElementById("shippingProgressMsg");

  const subtotal = getCartSubtotal();
  if (subtotalEl) {
    subtotalEl.textContent = "$" + subtotal.toLocaleString("es-CO") + " COP";
  }

  if (shippingBar && shippingMsg) {
    const pct = Math.min(100, Math.round((subtotal / FREE_SHIPPING_LIMIT) * 100));
    shippingBar.style.width = pct + "%";
    if (subtotal >= FREE_SHIPPING_LIMIT) {
      shippingMsg.innerHTML = "🎉 ¡Felicidades! Tienes <strong>ENVÍO GRATIS</strong> en Colombia";
      shippingBar.style.backgroundColor = "#0284C7";
    } else {
      const missing = FREE_SHIPPING_LIMIT - subtotal;
      shippingMsg.innerHTML = `Te faltan <strong>$${missing.toLocaleString("es-CO")} COP</strong> para Envío Gratis`;
      shippingBar.style.backgroundColor = "var(--color-primary)";
    }
  }

  if (!cartList) return;

  if (cart.length === 0) {
    cartList.innerHTML = `
      <div class="empty-cart-view">
        <svg width="60" height="60" viewBox="0 0 24 24" fill="none" stroke="#D1B8D9" stroke-width="1.5">
          <circle cx="9" cy="21" r="1"></circle>
          <circle cx="20" cy="21" r="1"></circle>
          <path d="M1 1h4l2.68 13.39a2 2 0 0 0 2 1.61h9.72a2 2 0 0 0 2-1.61L23 6H6"></path>
        </svg>
        <p>Tu bolsa de compras está vacía.</p>
        <a href="tienda.html" class="btn btn-outline btn-sm">Ver Catálogo</a>
      </div>
    `;
    return;
  }

  cartList.innerHTML = cart.map(item => `
    <div class="cart-item-row">
      <img src="${item.image || 'assets/img/logo.png'}" alt="${item.title}" class="cart-item-thumb" onerror="this.src='assets/img/logo.png'">
      <div class="cart-item-details">
        <h4 class="cart-item-name">${item.title}</h4>
        <span class="cart-item-variant">${item.variant}</span>
        <span class="cart-item-unit-price">$${item.price.toLocaleString("es-CO")} COP</span>
        <div class="cart-item-qty-ctrl">
          <button type="button" onclick="updateQuantity('${item.id}', '${item.variant}', -1)">-</button>
          <span>${item.quantity}</span>
          <button type="button" onclick="updateQuantity('${item.id}', '${item.variant}', 1)">+</button>
        </div>
      </div>
      <button type="button" class="cart-item-del-btn" onclick="removeFromCart('${item.id}', '${item.variant}')" title="Eliminar">
        &times;
      </button>
    </div>
  `).join("");
}

function openCart() {
  const drawer = document.getElementById("cartDrawer");
  const overlay = document.getElementById("cartOverlay");
  if (drawer && overlay) {
    drawer.classList.add("active");
    overlay.classList.add("active");
  }
}

function closeCart() {
  const drawer = document.getElementById("cartDrawer");
  const overlay = document.getElementById("cartOverlay");
  if (drawer && overlay) {
    drawer.classList.remove("active");
    overlay.classList.remove("active");
  }
}

function showToast(msg) {
  let toast = document.getElementById("appToast");
  if (!toast) {
    toast = document.createElement("div");
    toast.id = "appToast";
    toast.className = "app-toast";
    document.body.appendChild(toast);
  }
  toast.innerHTML = `<span>✨</span><span>${msg}</span>`;
  toast.classList.add("show");
  setTimeout(() => {
    toast.classList.remove("show");
  }, 2800);
}

function checkoutWhatsApp() {
  if (cart.length === 0) {
    showToast("Tu bolsa de compras está vacía.");
    return;
  }
  const subtotal = getCartSubtotal();
  const envioGratis = subtotal >= FREE_SHIPPING_LIMIT;
  
  let msg = "¡Hola Melinda's Makeup! 💖✨\n";
  msg += "Deseo confirmar el siguiente pedido desde la tienda web:\n\n";
  
  cart.forEach(item => {
    msg += `• ${item.quantity}x ${item.title} (${item.variant}) = $${(item.price * item.quantity).toLocaleString("es-CO")} COP\n`;
  });
  
  msg += `\n💰 *Subtotal:* $${subtotal.toLocaleString("es-CO")} COP\n`;
  msg += `🚚 *Envío:* ${envioGratis ? "¡GRATIS! (Meta superada)" : "Por coordinar con la asesora"}\n\n`;
  msg += "Por favor me indicas número de cuenta (Bold / PSE / Nequi / Bancolombia) y datos de despacho para entrega en Cali / Colombia. ¡Muchas gracias!";
  
  const url = `https://wa.me/${WHATSAPP_PHONE}?text=${encodeURIComponent(msg)}`;
  window.open(url, "_blank");
}

